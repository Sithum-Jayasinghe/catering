CREATE TABLE [Suppliers] (
    [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
    [SupplierCode] NVARCHAR(20) NOT NULL UNIQUE,
    [Name] NVARCHAR(200) NOT NULL,
    [RegistrationNumber] NVARCHAR(50) NOT NULL,
    [LegalName] NVARCHAR(200),
    [ContactPerson] NVARCHAR(100) NOT NULL,
    [ContactEmail] NVARCHAR(256) NOT NULL,
    [ContactPhone] NVARCHAR(20) NOT NULL,
    [TaxId] NVARCHAR(50),
    [VatNumber] NVARCHAR(50),
    [PaymentTerms] NVARCHAR(100),
    [CreditLimit] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [OutstandingBalance] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [Status] INT NOT NULL DEFAULT 1,
    [Category] INT NOT NULL DEFAULT 2,
    [OnTimeDeliveryRate] FLOAT NOT NULL DEFAULT 0,
    [QualityRate] FLOAT NOT NULL DEFAULT 100,
    [AverageLeadTimeDays] FLOAT NOT NULL DEFAULT 0,
    [TotalOrders] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalValue] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [Rating] FLOAT NOT NULL DEFAULT 0,
    [Notes] NVARCHAR(MAX),
    [DocumentsPath] NVARCHAR(500),
    [CreatedAt] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    [UpdatedAt] DATETIME2,
    [IsDeleted] BIT NOT NULL DEFAULT 0,
    [DeletedAt] DATETIME2,
    [DeletedBy] UNIQUEIDENTIFIER,
    [RowVersion] ROWVERSION
);
CREATE INDEX IX_Suppliers_Code ON Suppliers(SupplierCode) WHERE IsDeleted = 0;
CREATE INDEX IX_Suppliers_Status ON Suppliers(Status) WHERE IsDeleted = 0;