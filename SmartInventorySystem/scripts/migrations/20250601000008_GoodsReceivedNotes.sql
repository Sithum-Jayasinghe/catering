CREATE TABLE [GoodsReceivedNotes] (
    [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
    [GrnNumber] NVARCHAR(50) NOT NULL UNIQUE,
    [PurchaseOrderId] UNIQUEIDENTIFIER NOT NULL,
    [SupplierId] UNIQUEIDENTIFIER NOT NULL,
    [ReceivedBy] UNIQUEIDENTIFIER NOT NULL,
    [VerifiedBy] UNIQUEIDENTIFIER,
    [VerifiedAt] DATETIME2,
    [WarehouseId] UNIQUEIDENTIFIER NOT NULL,
    [StorageLocationId] UNIQUEIDENTIFIER NOT NULL,
    [DeliveryDate] DATETIME2 NOT NULL,
    [DeliveryNoteNumber] NVARCHAR(100),
    [VehicleNumber] NVARCHAR(20),
    [DriverName] NVARCHAR(100),
    [DriverContact] NVARCHAR(20),
    [ReceivedDate] DATETIME2 NOT NULL,
    [Status] INT NOT NULL DEFAULT 1,
    [TotalValue] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [InspectionNotes] NVARCHAR(500),
    [IsQualityPassed] BIT NOT NULL DEFAULT 0,
    [TotalQuantityAccepted] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalQuantityRejected] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [RejectionReason] NVARCHAR(500),
    [IsAiVerified] BIT NOT NULL DEFAULT 0,
    [AiVerificationResult] NVARCHAR(MAX),
    [InvoiceNumber] NVARCHAR(100),
    [IsPostedToInventory] BIT NOT NULL DEFAULT 0,
    [PostedAt] DATETIME2,
    [PostedBy] UNIQUEIDENTIFIER,
    [CreatedAt] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    [UpdatedAt] DATETIME2,
    [IsDeleted] BIT NOT NULL DEFAULT 0
);
CREATE INDEX IX_GRN_Number ON GoodsReceivedNotes(GrnNumber);
CREATE INDEX IX_GRN_Status ON GoodsReceivedNotes(Status);