CREATE TABLE [InventoryItems] (
    [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
    [ItemCode] NVARCHAR(50) NOT NULL UNIQUE,
    [Name] NVARCHAR(200) NOT NULL,
    [AlternativeNames] NVARCHAR(500),
    [Description] NVARCHAR(1000),
    [CategoryId] UNIQUEIDENTIFIER NOT NULL,
    [PrimarySupplierId] UNIQUEIDENTIFIER NOT NULL,
    [UnitOfMeasure] NVARCHAR(50) NOT NULL,
    [ReorderLevel] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [ReorderQuantity] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [MaximumStockLevel] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [MinimumStockLevel] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [StandardCost] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [CurrentPriceAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [CurrentPriceCurrency] NVARCHAR(3) NOT NULL DEFAULT N'LKR',
    [StorageType] INT NOT NULL DEFAULT 1,
    [TemperatureZone] INT NOT NULL DEFAULT 1,
    [ShelfLifeDays] INT NOT NULL DEFAULT 0,
    [IsPerishable] BIT NOT NULL DEFAULT 1,
    [IsBatchTracked] BIT NOT NULL DEFAULT 1,
    [IsActive] BIT NOT NULL DEFAULT 1,
    [IsDiscontinued] BIT NOT NULL DEFAULT 0,
    [Barcode] NVARCHAR(100),
    [QrCode] NVARCHAR(100),
    [Brand] NVARCHAR(100),
    [TotalQuantityOnHand] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalReservedQuantity] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [AverageUnitCost] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalInventoryValueAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalInventoryValueCurrency] NVARCHAR(3) NOT NULL DEFAULT N'LKR',
    [Status] INT NOT NULL DEFAULT 1,
    [SearchKeywords] NVARCHAR(MAX),
    [AISummary] NVARCHAR(MAX),
    [LastReceiptDate] DATETIME2,
    [LastIssueDate] DATETIME2,
    [ImageUrl] NVARCHAR(MAX),
    [LastForecastDate] DATETIME2,
    [PredictedDemand] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [DemandVariabilityIndex] FLOAT NOT NULL DEFAULT 0,
    [CreatedAt] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    [UpdatedAt] DATETIME2,
    [IsDeleted] BIT NOT NULL DEFAULT 0,
    [DeletedAt] DATETIME2,
    [DeletedBy] UNIQUEIDENTIFIER,
    [RowVersion] ROWVERSION,
    CONSTRAINT FK_InventoryItems_Category FOREIGN KEY (CategoryId) REFERENCES Categories(Id),
    CONSTRAINT FK_InventoryItems_Supplier FOREIGN KEY (PrimarySupplierId) REFERENCES Suppliers(Id)
);
CREATE INDEX IX_InventoryItems_ItemCode ON InventoryItems(ItemCode) WHERE IsDeleted = 0;
CREATE INDEX IX_InventoryItems_CategoryId ON InventoryItems(CategoryId) WHERE IsDeleted = 0;
CREATE INDEX IX_InventoryItems_Status ON InventoryItems(Status) WHERE IsDeleted = 0;