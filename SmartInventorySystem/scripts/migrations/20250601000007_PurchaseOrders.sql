CREATE TABLE [PurchaseOrders] (
    [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
    [PONumber] NVARCHAR(50) NOT NULL UNIQUE,
    [SupplierId] UNIQUEIDENTIFIER NOT NULL,
    [RequestedBy] UNIQUEIDENTIFIER NOT NULL,
    [ApprovedBy] UNIQUEIDENTIFIER,
    [ApprovedAt] DATETIME2,
    [IssuedBy] UNIQUEIDENTIFIER,
    [IssuedAt] DATETIME2,
    [Status] INT NOT NULL DEFAULT 1,
    [RequiredDate] DATETIME2 NOT NULL,
    [ExpectedDeliveryDate] DATETIME2,
    [ActualDeliveryDate] DATETIME2,
    [TotalAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [DiscountPercentage] DECIMAL(5,3) NOT NULL DEFAULT 0,
    [DiscountAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TaxAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [FreightCharges] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [GrandTotal] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [PaymentTerms] NVARCHAR(100),
    [ShippingTerms] NVARCHAR(100),
    [Notes] NVARCHAR(MAX),
    [AiRecommendation] NVARCHAR(MAX),
    [AiGeneratedDate] DATETIME2,
    [TotalLines] INT NOT NULL DEFAULT 0,
    [TotalQuantityOrdered] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalQuantityReceived] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [ShipToWarehouseId] UNIQUEIDENTIFIER,
    [CreatedAt] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    [UpdatedAt] DATETIME2,
    [IsDeleted] BIT NOT NULL DEFAULT 0,
    CONSTRAINT FK_PurchaseOrders_Supplier FOREIGN KEY (SupplierId) REFERENCES Suppliers(Id)
);
CREATE INDEX IX_PurchaseOrders_PONumber ON PurchaseOrders(PONumber);
CREATE INDEX IX_PurchaseOrders_Status ON PurchaseOrders(Status);

CREATE TABLE [PurchaseOrderLines] (
    [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
    [PurchaseOrderId] UNIQUEIDENTIFIER NOT NULL,
    [ItemId] UNIQUEIDENTIFIER NOT NULL,
    [LineNumber] INT NOT NULL,
    [ItemCode] NVARCHAR(50) NOT NULL,
    [ItemName] NVARCHAR(200),
    [UnitOfMeasure] NVARCHAR(50) NOT NULL,
    [QuantityOrdered] DECIMAL(18,3) NOT NULL,
    [QuantityReceived] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [QuantityReturned] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [UnitPrice] DECIMAL(18,3) NOT NULL,
    [LineAmount] DECIMAL(18,3) NOT NULL,
    [TaxAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [DiscountAmount] DECIMAL(18,3) NOT NULL DEFAULT 0,
    [TotalAmount] DECIMAL(18,3) NOT NULL,
    [RequiredDeliveryDate] DATETIME2,
    [Notes] NVARCHAR(500),
    [AccountCode] NVARCHAR(50),
    [Department] NVARCHAR(100),
    [CreatedAt] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_POLines_PO FOREIGN KEY (PurchaseOrderId) REFERENCES PurchaseOrders(Id) ON DELETE CASCADE
);